const boton = document.getElementById("R1");
const caja = document.getElementById("preg1");

boton.addEventListener("click", () => {
  // Comprobamos si el contenedor está visible actualmente
  if (caja.style.display === "block") {
    // Si ya es visible, lo volvemos a ocultar
    caja.style.display = "none";
    boton.innerText = "Mostrar Respuesta 👀";
  } else {
    // Si está oculto, lo mostramos en pantalla
    caja.style.display = "block";
    boton.innerText = "Ocultar Respuesta 🙈";
  }
});


